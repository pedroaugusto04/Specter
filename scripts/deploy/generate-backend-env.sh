#!/usr/bin/env bash
set -euo pipefail

OUTPUT_FILE="${1:-.deploy/backend.env}"
DEFAULT_PORT="${2:-3001}"

mkdir -p "$(dirname "$OUTPUT_FILE")"
> "$OUTPUT_FILE"

write_kv() {
  local key="$1"
  local value="${2-}"
  printf '%s=%s\n' "$key" "$value" >> "$OUTPUT_FILE"
}

write_kv NODE_ENV "production"
write_kv PORT "${APP_PORT:-$DEFAULT_PORT}"
write_kv HOST "${HOST:-0.0.0.0}"

# Production defaults for Specter
POSTGRES_USER="${POSTGRES_USER:-postgres}"
POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-postgres}"
POSTGRES_DB="${POSTGRES_DB:-specter}"
DATABASE_URL="${DATABASE_URL:-postgresql://${POSTGRES_USER}:${POSTGRES_PASSWORD}@postgres:5432/${POSTGRES_DB}}"
REDIS_URL="${REDIS_URL:-redis://redis:6379}"
REDIS_HOST="${REDIS_HOST:-redis}"
REDIS_PORT="${REDIS_PORT:-6379}"
CORS_ORIGIN="${CORS_ORIGIN:-https://specterdev.online,http://specterdev.online,https://www.specterdev.online,http://www.specterdev.online,https://pedro-duarte.ddns.net,http://pedro-duarte.ddns.net,https://pedro-duarte.servehttp.com,http://pedro-duarte.servehttp.com}"
COMPILER_PROVIDER="${COMPILER_PROVIDER:-agy}"
NOTIFICATION_PROVIDER="${NOTIFICATION_PROVIDER:-console}"
NOTIFICATION_FROM_EMAIL="${NOTIFICATION_FROM_EMAIL:-onboarding@resend.dev}"
RESEND_API_KEY="${RESEND_API_KEY:-}"
LOG_LEVEL="${LOG_LEVEL:-info}"
SCRAPER_ENGINE="${SCRAPER_ENGINE:-playwright}"

# Guardrail: If NOTIFICATION_PROVIDER is resend but RESEND_API_KEY is not provided,
# warn and safely fall back to console to prevent container boot crash loops.
if [ "$NOTIFICATION_PROVIDER" = "resend" ] && [ -z "${RESEND_API_KEY:-}" ]; then
  echo "WARNING: NOTIFICATION_PROVIDER is 'resend', but RESEND_API_KEY is missing."
  echo "   Using NOTIFICATION_PROVIDER='console' so the backend can start."
  NOTIFICATION_PROVIDER="console"
fi

keys=(
  POSTGRES_USER
  POSTGRES_PASSWORD
  POSTGRES_DB
  DATABASE_URL
  REDIS_URL
  REDIS_HOST
  REDIS_PORT
  CORS_ORIGIN
  LOG_LEVEL
  COMPILER_PROVIDER
  COMPILER_API_MODEL
  COMPILER_API_KEY
  COMPILER_API_BASE_URL
  COMPILER_API_MAX_RETRIES
  COMPILER_API_RETRY_BASE_DELAY_MS
  COMPILER_API_RETRY_MAX_DELAY_MS
  COMPILER_RATE_LIMIT_RETRY_DELAY_MS
  EVALS_LIVE_MODELS_ENABLED
  AGY_CLI_PATH
  AGY_MODEL
  CODEX_CLI_PATH
  COMPILER_CODEX_MODEL
  CODEX_SANDBOX
  COMPILER_TEMP_DIR
  COMPILER_TIMEOUT_MS
  COMPILER_CONCURRENCY
  SCRAPER_ENGINE
  SCRAPER_CONCURRENCY
  PLAYWRIGHT_TIMEOUT_MS
  SEMANTIC_REVIEW_ENABLED
  SEMANTIC_REVIEW_THRESHOLD
  EXTRACTION_ACTION_TIMEOUT_MS
  EXTRACTION_POLL_INTERVAL_MS
  EXTRACTION_MAX_EVIDENCE
  EXTRACTION_EVIDENCE_RETENTION_DAYS
  CONFIGURATION_REVIEW_RESERVE_MS
  COMPILER_MAX_OUTPUT_CHARS
  COMPILER_MAX_OUTPUT_TOKENS
  CONFIGURATION_MAX_DECISIONS
  NOTIFICATION_TIMEOUT_MS
  NOTIFICATION_MAX_ATTEMPTS
  EXTRACTION_MAX_PAGES
  EXTRACTION_MAX_ACTIONS
  EXTRACTION_MAX_ITEMS
  ACQUISITION_MAX_ATTEMPTS
  ACCESS_BLOCK_THRESHOLD
  ACCESS_BLOCK_COOLDOWN_MINUTES
  EXTRACTION_TIMEOUT_MS
  COMPILATION_BUDGET_MS
  COMPILATION_MAX_ATTEMPTS
  COMPILATION_QUEUE_MAX_ATTEMPTS
  CONFIGURATION_MAX_INPUT_CHARS
  COMPILATION_DIAGNOSTICS_ENABLED
  COMPILATION_DIAGNOSTICS_MAX_CHARS
  HEALING_WINDOW_MS
  MIN_CRON_INTERVAL_MINUTES
  CONSECUTIVE_FAILURES_FOR_HEALING
  MAX_HEALING_RETRIES
  RETENTION_DAYS_UNCHANGED
  DEFAULT_MAX_ACTIVE_MONITORS
  DEFAULT_MAX_MONTHLY_COMPILATIONS
  DEFAULT_MAX_MONTHLY_EXECUTIONS
  NOTIFICATION_PROVIDER
  RESEND_API_KEY
  NOTIFICATION_FROM_EMAIL
  TELEGRAM_BOT_TOKEN
  NEXT_PUBLIC_API_URL
  NEXT_PUBLIC_BASE_PATH
  NEXT_PUBLIC_EXTENSION_URL
  DOCKER_LOG_MAX_SIZE
  DOCKER_LOG_MAX_FILE
  ZENROWS_API_KEY
  SCRAPERAPI_KEY
  SCRAPINGBEE_API_KEY
  CRAWLBASE_TOKEN
  DECODO_API_KEY
  UNBLOCKER_TIMEOUT_MS
  HTTP_PROXY
  HTTP_FALLBACK_PROXY
  JWT_SECRET
  ENCRYPTION_KEY
  JWT_ACCESS_EXPIRES_SECONDS
  JWT_REFRESH_EXPIRES_SECONDS
  COOKIE_SECURE
  FRONTEND_URL
  GOOGLE_CLIENT_ID
  GOOGLE_CLIENT_SECRET
  GOOGLE_CALLBACK_URL
  SUPABASE_URL
  SUPABASE_SERVICE_ROLE_KEY
  SUPABASE_STORAGE_BUCKET
)

for key in "${keys[@]}"; do
  val="${!key:-}"
  if [ -n "$val" ]; then
    write_kv "$key" "$val"
  fi
done

chmod 600 "$OUTPUT_FILE"


